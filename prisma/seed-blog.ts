async function main() {
  let created = 0;
  let kept = 0;
  for (const article of articles) {
    const wordCount = article.content.reduce(
      (count, block) =>
        count +
        (block.type === 'list'
          ? (block.items ?? []).join(' ').split(/\s+/).filter(Boolean).length
          : (block.text ?? '').split(/\s+/).filter(Boolean).length),
      0,
    );
    const articleData = {
      ...article,
      authorName: 'تحریریه هلپر',
      authorRole: 'راهنمای خدمات',
      readingMinutes: Math.max(1, Math.ceil(wordCount / 220)),
    };
    const existing = await prisma.blogPost.findUnique({
      where: { slug: article.slug },
      select: { id: true, publishedAt: true },
    });
    if (existing) {
      kept += 1;
      continue;
    }
    await prisma.blogPost.create({
      data: {
        ...articleData,
        status: 'PUBLISHED',
        publishedAt: new Date(),
      },
    });
    created += 1;
  }
  console.log(
    `Created ${created} articles; kept ${kept} existing slugs unchanged.`,
  );
}

main()
  .catch((error: unknown) => {
    console.error('Blog seeding failed:', error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
